  @Test
  fun `FIR capture preserves overloads and generic specializations`(@TempDir directory: Path) {
    val fir = directory.resolve("kpaths.fir.txt")
    compileSuccessfully(
      directory,
      """
        package fixture
        import dev.kpaths.annotations.Pathable
        @Pathable data class Box<T>(val value: T)
        val text = Box.Paths.of<String>().value
        val count = Box.Paths.of(Int::class).value
      """,
      firSnapshot = fir,
    )
    val output = Files.readString(fir)
    assertEquals(2, Regex("fixture/Box\\.Paths\\.of\\n").findAll(output).count())
    assertEquals(2, Regex("fixture/Box\\.Paths\\.__kpaths_Catalog\\.value\\n").findAll(output).count())
    assertContains(output, "fixture/Box<kotlin/String>")
    assertContains(output, "fixture/Box<kotlin/Int>")
  }

